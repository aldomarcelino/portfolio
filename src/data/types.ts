export type SocialLink = { label: string; url: string };
export type SkillGroup = { category: string; items: string[] };
export type Profile = {
  name: string;
  title: string;
  email: string;
  location: string;
  summary: string;
  resume: string;
  socials: SocialLink[];
  skills: SkillGroup[];
};
export type Project = {
  id: string;
  name: string;
  category: string;
  role: string;
  description: string;
  stack: string[];
  details: string[];
  status: "Live product" | "Archived" | "Prototype";
  team: string;
  outcome: { value: string; label: string };
  cover: { src: string; alt: string; mobile?: boolean };
  screenshots: { src: string; caption: string; width: number; height: number; placeholder?: boolean }[];
  demo: { src?: string; poster: string };
  liveUrl?: string;
  sourceUrl?: string;
};
export type Experience = {
  company: string;
  role: string;
  period: string;
  location: string;
  description: string;
  highlights: string[];
  stack: string[];
  quality: string;
  products: { name: string; url: string }[];
};
